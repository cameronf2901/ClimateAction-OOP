    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        try{
        java.io.FileWriter writer = new java.io.FileWriter("energycost.txt");
        // Save whatever is currently shown as the total cost
        writer.write(lblTotalCost.getText());

        writer.close();
        JOptionPane.showMessageDialog(this, "Cost saved successfully!");
        }catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error saving cost to file.");
    }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        try{
        java.io.File file = new java.io.File("energycost.txt");
        java.util.Scanner sc = new java.util.Scanner(file);

        String loadedLine = "";
        if (sc.hasNextLine()) {
            loadedLine = sc.nextLine();   // e.g. "Total cost: €3.50"
        }
        sc.close();

        if (!loadedLine.isEmpty()) {
            lblTotalCost.setText(loadedLine);
            JOptionPane.showMessageDialog(this, "Cost loaded from file.");
        } else {
            JOptionPane.showMessageDialog(this, "File is empty.");
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error loading cost from file.");
    }
    }//GEN-LAST:event_jButton2ActionPerformed

