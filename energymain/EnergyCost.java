    private void btnCalculateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalculateActionPerformed
        // TODO add your handling code here:
         String rateText = txtRate.getText().trim();

        if (rateText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a cost per kWh.");
            return;
        }

        try {
            double rate = Double.parseDouble(rateText);

            double totalKwh = EnergyInput.calc.getTotalKwh();
            double totalCost = totalKwh * rate;

            lblTotalCost.setText("Total cost: €" + String.format("%.2f", totalCost));

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter a valid number for the cost.");
        }
    }//GEN-LAST:event_btnCalculateActionPerformed

